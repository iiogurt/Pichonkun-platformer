// Builds the tile grid for a level from its chunks.
function buildLevelGrid(def) {
  const H = 15;
  let W = 0;
  for (const ch of def.chunks) W += Math.max(...ch.map(r => r.length));
  const grid = [];
  for (let y = 0; y < H; y++) grid.push(new Array(W).fill(' '));
  let ox = 0;
  for (const ch of def.chunks) {
    const cw = Math.max(...ch.map(r => r.length));
    const oy = H - ch.length;
    ch.forEach((row, ry) => {
      for (let x = 0; x < row.length; x++) grid[oy + ry][ox + x] = row[x];
    });
    ox += cw;
  }
  // Gates and doors extend upward to the ceiling
  for (let x = 0; x < W; x++) for (let y = H - 1; y >= 0; y--) {
    const c = grid[y][x];
    if ((c === 'G' || c === 'D') && y > 0 && grid[y - 1][x] === ' ') grid[y - 1][x] = c;
  }
  return { grid, W, H };
}
